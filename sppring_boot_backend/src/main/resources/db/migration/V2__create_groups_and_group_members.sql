DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'group_privacy') THEN
        CREATE TYPE group_privacy AS ENUM ('public', 'private');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'group_status') THEN
        CREATE TYPE group_status AS ENUM ('active', 'closed');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'group_member_role') THEN
        CREATE TYPE group_member_role AS ENUM ('admin', 'moderator', 'member');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    group_image VARCHAR(255),
    cover_image VARCHAR(255),
    privacy group_privacy NOT NULL DEFAULT 'public',
    created_by INTEGER NOT NULL REFERENCES users(id),
    status group_status NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_groups_name ON groups (name);
CREATE INDEX IF NOT EXISTS ix_groups_created_by ON groups (created_by);
CREATE INDEX IF NOT EXISTS ix_groups_id ON groups (id);

CREATE TABLE IF NOT EXISTS group_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES groups(id),
    user_id INTEGER NOT NULL REFERENCES users(id),
    role group_member_role NOT NULL DEFAULT 'member',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_group_members_group_user ON group_members (group_id, user_id);
CREATE INDEX IF NOT EXISTS ix_group_members_group_user ON group_members (group_id, user_id);
CREATE INDEX IF NOT EXISTS ix_group_members_id ON group_members (id);
