DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'settings_frequency') THEN
        CREATE TYPE settings_frequency AS ENUM ('daily', 'weekly', 'monthly', 'custom_days');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'join_request_status') THEN
        CREATE TYPE join_request_status AS ENUM ('pending', 'approved', 'rejected');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'cycle_frequency') THEN
        CREATE TYPE cycle_frequency AS ENUM ('daily', 'weekly', 'monthly', 'custom_days');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'cycle_status') THEN
        CREATE TYPE cycle_status AS ENUM ('pending', 'active', 'paused', 'completed');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payment_status') THEN
        CREATE TYPE payment_status AS ENUM ('due', 'paid', 'late');
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payout_status') THEN
        CREATE TYPE payout_status AS ENUM ('pending', 'approved', 'rejected', 'paid');
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS group_settings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES groups(id),
    contribution_amount NUMERIC(12, 2) NOT NULL,
    frequency settings_frequency NOT NULL,
    custom_days INTEGER,
    allow_late BOOLEAN NOT NULL DEFAULT FALSE,
    late_penalty NUMERIC(12, 2),
    auto_start_cycle BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_group_settings_group_id UNIQUE (group_id)
);

CREATE TABLE IF NOT EXISTS invites (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES groups(id),
    created_by INTEGER NOT NULL REFERENCES users(id),
    code VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_invites_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS join_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status join_request_status NOT NULL DEFAULT 'pending',
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    handled_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS cycles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES groups(id),
    created_by INTEGER NOT NULL REFERENCES users(id),
    start_date DATE NOT NULL,
    end_date DATE,
    frequency cycle_frequency NOT NULL,
    custom_days INTEGER,
    status cycle_status NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cycle_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id INTEGER NOT NULL REFERENCES cycles(id),
    user_id INTEGER NOT NULL REFERENCES users(id),
    payout_order INTEGER NOT NULL,
    received BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uc_cycle_user UNIQUE (cycle_id, user_id)
);

CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id INTEGER NOT NULL REFERENCES cycles(id),
    cycle_member_id INTEGER NOT NULL REFERENCES cycle_members(id),
    created_by INTEGER NOT NULL REFERENCES users(id),
    due_date DATE NOT NULL,
    amount_due NUMERIC(12, 2) NOT NULL,
    amount_paid NUMERIC(12, 2) NOT NULL DEFAULT 0,
    status payment_status NOT NULL DEFAULT 'due',
    paid_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payments_cycle_member_due_date UNIQUE (cycle_member_id, due_date)
);

CREATE TABLE IF NOT EXISTS payouts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id INTEGER NOT NULL REFERENCES cycles(id),
    cycle_member_id INTEGER NOT NULL REFERENCES cycle_members(id),
    created_by INTEGER NOT NULL REFERENCES users(id),
    approved_by INTEGER REFERENCES users(id),
    amount NUMERIC(12, 2) NOT NULL,
    status payout_status NOT NULL DEFAULT 'pending',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    approved_at TIMESTAMPTZ,
    paid_at TIMESTAMPTZ,
    CONSTRAINT uq_payouts_cycle_member UNIQUE (cycle_member_id)
);

CREATE INDEX IF NOT EXISTS ix_group_settings_id ON group_settings (id);
CREATE INDEX IF NOT EXISTS ix_invites_group_id ON invites (group_id);
CREATE INDEX IF NOT EXISTS ix_join_requests_group_id ON join_requests (group_id);
CREATE INDEX IF NOT EXISTS ix_join_requests_user_id ON join_requests (user_id);
CREATE INDEX IF NOT EXISTS ix_join_requests_status ON join_requests (status);
CREATE INDEX IF NOT EXISTS ix_cycles_group_id ON cycles (group_id);
CREATE INDEX IF NOT EXISTS ix_cycles_created_by ON cycles (created_by);
CREATE INDEX IF NOT EXISTS ix_cycle_order ON cycle_members (cycle_id, payout_order);
CREATE INDEX IF NOT EXISTS ix_payments_cycle_id_status ON payments (cycle_id, status);
CREATE INDEX IF NOT EXISTS ix_payments_cycle_member_due_date ON payments (cycle_member_id, due_date);
CREATE INDEX IF NOT EXISTS ix_payouts_cycle_id_status ON payouts (cycle_id, status);
CREATE INDEX IF NOT EXISTS ix_payouts_cycle_member_id ON payouts (cycle_member_id);
